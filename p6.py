#Write a program to illustrate the use of tuples and sets with basic operations. 

#tuple:

colors= ('red','blue','white')
print(colors)

#indexing in tuple:

print('first item:',colors[0])
print('second item:',colors[-1])
print('slicing [0:2]:',colors[0:2])

#set:

name= ['shital','nisha','hetvi']
print(name)

#indexing in set:

print('first name:',name[0])
print('second name:',name[-1])
print('last name:',name[0:2])
