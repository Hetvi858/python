#Write a program to perform mathematical operations using math module.


import math

a = 16
b = 5

print("Addition =", a + b)
print("Subtraction =", a - b)
print("Multiplication =", a * b)
print("Division =", a / b)

print("Square Root =", math.sqrt(a))
print("Power =", math.pow(a, 2))
print("Factorial =", math.factorial(b))
print("Ceiling =", math.ceil(4.3))
print("Floor =", math.floor(4.8))

